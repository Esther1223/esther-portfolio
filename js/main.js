const html = document.documentElement;
const langToggle = document.getElementById("lang-toggle");
const themeToggle = document.getElementById("theme-toggle");
const yearEl = document.getElementById("year");

const storedLang = localStorage.getItem("portfolio-lang");
const storedTheme = localStorage.getItem("portfolio-theme");
const prefersDark = window.matchMedia("(prefers-color-scheme: dark)").matches;

let lang = storedLang === "en" || storedLang === "zh" ? storedLang : "zh";
let theme = storedTheme === "light" || storedTheme === "dark" ? storedTheme : prefersDark ? "dark" : "light";

function applyTheme(next) {
  theme = next;
  html.setAttribute("data-theme", theme);
  localStorage.setItem("portfolio-theme", theme);
  themeToggle.setAttribute(
    "aria-label",
    theme === "dark" ? "Switch to light theme" : "Switch to dark theme"
  );
}

function applyLang(next) {
  lang = next;
  const dict = translations[lang];
  html.setAttribute("lang", lang === "zh" ? "zh-Hant" : "en");
  localStorage.setItem("portfolio-lang", lang);
  langToggle.textContent = lang === "zh" ? "EN" : "中文";
  langToggle.setAttribute(
    "aria-label",
    lang === "zh" ? "Switch to English" : "切換為中文"
  );

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
}

langToggle.addEventListener("click", () => applyLang(lang === "zh" ? "en" : "zh"));
themeToggle.addEventListener("click", () => applyTheme(theme === "dark" ? "light" : "dark"));

applyTheme(theme);
applyLang(lang);

if (yearEl) yearEl.textContent = String(new Date().getFullYear());

const sections = document.querySelectorAll(".section");
if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );
  sections.forEach((section) => observer.observe(section));
} else {
  sections.forEach((section) => section.classList.add("is-visible"));
}
